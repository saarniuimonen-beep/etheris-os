#!/usr/bin/env bash
# Record docker.io/archlinux digest for more repeatable bakes.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IMAGE="${ETHERIS_BUILD_IMAGE:-docker.io/archlinux:latest}"
PIN="$ROOT/out/build-image.pin"

mkdir -p "$ROOT/out"
echo "Resolving digest for $IMAGE …"
if ! command -v podman >/dev/null; then
  echo "podman required" >&2
  exit 1
fi
PODMAN=(podman)
sudo -n true 2>/dev/null && PODMAN=(sudo podman)

"${PODMAN[@]}" pull "$IMAGE"
digest="$("${PODMAN[@]}" image inspect "$IMAGE" --format '{{.Digest}}')"
[[ -n "$digest" && "$digest" != "<no value>" ]] || {
  echo "Could not read digest" >&2
  exit 1
}

# Prefer repo@digest form
ref="${IMAGE%%:*}@${digest}"
cat >"$PIN" <<EOF
# Generated by scripts/pin-build-image.sh — $(date -u +%Y-%m-%dT%H:%M:%SZ)
# build.sh uses this when ETHERIS_BUILD_IMAGE is unset.
ETHERIS_BUILD_IMAGE=${ref}
SOURCE_IMAGE=${IMAGE}
DIGEST=${digest}
EOF
echo "Wrote $PIN"
echo "  $ref"
